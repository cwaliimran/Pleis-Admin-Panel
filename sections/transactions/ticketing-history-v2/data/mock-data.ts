const cloneExtra = (base: Ticket, offset: number): Ticket => {
  const suffix = `-x${offset}`;
  return { ...base, id: `${base.id}${suffix}`, ticketId: `${base.ticketId}${suffix}` };
};

const buildAllTickets = (): Ticket[] => {
  const all = [...MOCK_TICKETS];
  let offset = 0;
  while (all.length < MOCK_TOTAL_RECORDS) {
    all.push(cloneExtra(MOCK_TICKETS[offset % MOCK_TICKETS.length], offset));
    offset += 1;
  }
  return all;
};

