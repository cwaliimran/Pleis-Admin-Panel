const cloneExtra = (base: LoyaltyEntry, offset: number): LoyaltyEntry => {
  const suffix = `-x${offset}`;
  return { ...base, id: `${base.id}${suffix}`, transactionId: base.transactionId ? `${base.transactionId}${suffix}` : null };
};

const buildAllEntries = (): LoyaltyEntry[] => {
  const all = [...MOCK_LOYALTY_ENTRIES];
  let offset = 0;
  while (all.length < MOCK_TOTAL_RECORDS) {
    all.push(cloneExtra(MOCK_LOYALTY_ENTRIES[offset % MOCK_LOYALTY_ENTRIES.length], offset));
    offset += 1;
  }
  return all;
};

export const ALL_MOCK_LOYALTY_ENTRIES: LoyaltyEntry[] = buildAllEntries();
