export const MOCK_TOTAL_RECORDS = 27;

const cloneExtra = (base: Order, offset: number): Order => {
  const suffix = `-x${offset}`;
  return { ...base, id: `${base.id}${suffix}`, orderReference: `${base.orderReference}${suffix}` };
};

const buildAllOrders = (): Order[] => {
  const all = [...MOCK_ORDERS];
  let offset = 0;
  while (all.length < MOCK_TOTAL_RECORDS) {
    all.push(cloneExtra(MOCK_ORDERS[offset % MOCK_ORDERS.length], offset));
    offset += 1;
  }
  return all;
};

export const ALL_MOCK_ORDERS: Order[] = buildAllOrders();
